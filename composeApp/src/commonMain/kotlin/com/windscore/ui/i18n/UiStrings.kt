/**
 * 支持的语言。代码用于持久化，[nativeName] 用于设置页展示（始终以该语言自身书写）。
 */
enum class AppLanguage(val code: String, val nativeName: String) {
    ENGLISH("en", "English"),
    CHINESE("zh", "中文"),
    JAPANESE("ja", "日本語");

    companion object {
        fun fromCode(code: String?): AppLanguage? = entries.firstOrNull { it.code == code }
    }
}

/**
 * 全局语言状态（Compose 可观察）。启动时由持久化层覆盖默认值；设置页通过 [update] 切换。
 */
object AppStrings {
    var language by mutableStateOf(AppLanguage.CHINESE)
        private set

    fun update(lang: AppLanguage) {
        language = lang
    }
}

